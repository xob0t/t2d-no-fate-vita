"""Write compile-only stubs for the Unity 6 engine binding calls (*_Injected) the game's code names,
as Compat2018.Injected.<Type>_<Member>(...), from RewindStats `apigap` TSVs and the call sites in the
(mechfix'd) source, which say whether a by-reference parameter is `ref` or `out`.

    python -I gen_injected.py <out.cs> <src dir> <apigap tsv>...
"""
import csv
import os
import re
import sys

csv.field_size_limit(1 << 30)
PRIM = {
    'System.Void': 'void', 'System.Boolean': 'bool', 'System.Int32': 'int', 'System.UInt32': 'uint',
    'System.Int64': 'long', 'System.UInt64': 'ulong', 'System.Single': 'float', 'System.Double': 'double',
    'System.Int16': 'short', 'System.UInt16': 'ushort', 'System.Byte': 'byte', 'System.SByte': 'sbyte',
    'System.String': 'string', 'System.Object': 'object', 'System.Char': 'char',
}
# Unity 6 types 2018.2 lacks: their values pass through as integers.
MISSING = {'UnityEngine.Networking.UnityWebRequest/Result': 'int',
           'UnityEngine.Experimental.Rendering.GraphicsFormat': 'int'}


def cs_type(t):
    if t in PRIM:
        return PRIM[t]
    if t in MISSING:
        return MISSING[t]
    return 'global::' + t.replace('/', '.')


def split_params(s):
    out, depth, cur = [], 0, ''
    for c in s:
        if c == ',' and depth == 0:
            out.append(cur.strip())
            cur = ''
            continue
        depth += c in '<'
        depth -= c in '>'
        cur += c
    if cur.strip():
        out.append(cur.strip())
    return out


def main():
    out, src, tsvs = sys.argv[1], sys.argv[2], sys.argv[3:]
    calls = {}
    for root, _, files in os.walk(src):
        for f in files:
            if f.endswith('.cs'):
                with open(os.path.join(root, f), encoding='utf-8-sig') as fh:
                    for m in re.finditer(r'Compat2018\.Injected\.(\w+)\(([^;]*)', fh.read()):
                        calls.setdefault(m.group(1), m.group(2))
    sigs = {}
    for path in tsvs:
        with open(path, encoding='utf-8') as fh:
            for r in csv.DictReader(fh, delimiter='\t'):
                m = re.match(r'^([\w./]+)::(\w+_Injected)\((.*)\) : (.+)$', r['api'])
                if not m:
                    continue
                typ, name, params, ret = m.groups()
                key = typ.split('.')[-1].split('/')[-1] + '_' + name
                sigs[key] = (params, ret)
    lines = ['// Generated by gen_injected.py. COMPILE-ONLY stubs for Unity 6 engine binding calls.',
             'namespace Compat2018', '{', '    public static class Injected', '    {']
    for key in sorted(sigs):
        params, ret = sigs[key]
        call = calls.get(key, '')
        ps = []
        for i, p in enumerate(split_params(params)):
            if p.endswith('&'):
                mode = 'out' if re.search(r'(^|[(,]\s*)out\s', call) and ('out ' in call.split(',')[i] if i < len(call.split(',')) else False) else 'ref'
                ps.append('%s %s p%d' % (mode, cs_type(p[:-1]), i))
            else:
                ps.append('%s p%d' % (cs_type(p), i))
        body = 'throw new System.NotSupportedException();'
        lines.append('        public static %s %s(%s) { %s }' % (cs_type(ret), key, ', '.join(ps), body))
    lines += ['    }', '}', '']
    with open(out, 'w', encoding='utf-8') as fh:
        fh.write('\n'.join(lines))
    used = set(calls)
    print('%d stubs; %d call-site names without a signature: %s' % (len(sigs), len(used - set(sigs)), ', '.join(sorted(used - set(sigs)))))


if __name__ == '__main__':
    main()
