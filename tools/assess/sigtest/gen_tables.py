"""Writes SigTestTables.cs: long runs of element stores and reads on arrays of several element types, and of
interface type tests.

    python -I tools/assess/sigtest/gen_tables.py <out.cs> [stores per method]

build_sigtest.py runs it into its work dir; the file is generated, not kept in the repository.

Terminator 2D's asset-table initializers store thousands of constants into double[] arrays, and in its Master
build MSVC kept double[]'s bounds-checked SetAt as a function of its own (0x1800026F0, 2,438 calls). In a small
test method the accessor is inlined, so the signature library has no SetAt for double[]. Methods this large make
the compiler keep the accessors out of line, as it did in the game (400 stores per method were not enough for
value types; the game's int[] SetAt stayed out of line in a method with 1,211 stores).
"""
import sys
from pathlib import Path

STORES = 2500
TYPES = [
    ('Doubles', 'double', lambda i: f'{i * 0.5 + 0.25!r}'),
    ('Floats', 'float', lambda i: f'{i * 0.25 + 0.125!r}f'),
    ('Ints', 'int', lambda i: str(i * 7 - 3)),
    ('Longs', 'long', lambda i: f'{i * 1000003 + 11}L'),
    ('Strings', 'string', lambda i: f'"s{i}"'),
    ('Objects', 'object', lambda i: f'Names[{i % 3}]'),
    ('Bools', 'bool', lambda i: 'true' if i % 3 else 'false'),
    ('Bytes', 'byte', lambda i: str(i % 251)),
]
READS = [('Doubles', 'double'), ('Floats', 'float'), ('Ints', 'int')]


def main():
    if len(sys.argv) not in (2, 3):
        sys.exit(__doc__)
    stores = int(sys.argv[2]) if len(sys.argv) == 3 else STORES
    lines = ['// Generated by gen_tables.py: long runs of element stores into arrays of several element types, like the',
             "// asset-table initializers of Haxe-generated games. In a function this large MSVC's link-time code generation",
             "// stops inlining the arrays' bounds-checked SetAt accessors, so they stay functions with symbols of their own.",
             'namespace SigTest', '{', '    public static class BigTables', '    {']
    for name, typ, value in TYPES:
        lines += [f'        public static {typ}[] {name}(int n)', '        {', f'            var a = new {typ}[n];']
        lines += [f'            a[{i}] = {value(i)};' for i in range(stores)]
        lines += ['            return a;', '        }', '']
    # Long runs of element reads too, for the arrays' GetAt.
    for name, typ in READS:
        lines += [f'        public static {typ} Sum{name}({typ}[] a)', '        {', f'            {typ} s = 0;']
        lines += [f'            s += a[{i}];' for i in range(stores)]
        lines += ['            return s;', '        }', '']
    # Interface type tests (IL2CPP's general IsInst, which the game calls out of line), each on another element.
    interfaces = ['IShape', 'System.IDisposable', 'System.IFormattable', 'System.Collections.IEnumerable', 'System.IComparable<Shape>']
    lines += ['        public static int Casts(object[] o)', '        {', '            int n = 0;']
    lines += [f'            if (o[{i}] is {interfaces[i % len(interfaces)]}) n += {i % 13 + 1};' for i in range(stores)]
    lines += ['            return n;', '        }', '']
    lines += ['        static readonly string[] Names = { "a", "b", "c" };', '',
              '        public static int All(int n)', '        {',
              '            int length = ' + ' + '.join(f'{name}(n).Length' for name, _, _ in TYPES) + ';',
              '            return length + Casts(Objects(n)) + ' + ' + '.join(f'(int)Sum{name}({name}(n))' for name, _ in READS) + ';',
              '        }', '    }', '}', '']
    Path(sys.argv[1]).write_text('\n'.join(lines), encoding='utf-8', newline='\n')


if __name__ == '__main__':
    main()
